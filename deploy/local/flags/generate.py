"""Write the production feature flags into one env file per local service.

The source is backend/deploy/runtime_env.yaml, the composed production
environment. The fork removed it in 0e210166c3, so it is read from the commit
before that. Run from the repo root:

    python3 deploy/local/flags/generate.py

Infrastructure settings and flags that need a service the local stack does
not have are left out; EXCLUDE says why for each rule. docker-compose.yaml
loads these files before .env and its own `environment`, so local values win.
"""

import re
import subprocess
from pathlib import Path

import yaml

SOURCE_COMMIT = '0e210166c3^'
SOURCE_PATH = 'backend/deploy/runtime_env.yaml'
OUT_DIR = Path(__file__).resolve().parent

EXCLUDE: list[tuple[str, str]] = [
    # Production infrastructure: addresses, identities, credentials, telemetry.
    (r'URL|URIS?$|_HOST$|PORT$|ENDPOINT', 'production addresses'),
    (r'PROJECT|REGION|LOCATION|NAMESPACE|GCP|GCS|GOOGLE|BUCKET|PUBSUB|TOPIC', 'Google Cloud resources'),
    (r'SECRET|_KEY$|TOKEN|PASSWORD|_SA$|SERVICE_ACCOUNT|INVOKER|CLIENT_ID|_SID$', 'credentials'),
    (r'OTEL|SENTRY|POSTHOG|METRICS|READ_LEDGER', 'telemetry to Omi services'),
    (r'RELEASE|BUILD|VERSION|IMAGE|REVISION', 'deploy identity'),
    (r'^OMI_ENV_STAGE$|ALLOW_PROD', 'local stage is set in docker-compose.yaml'),
    (r'_DISPATCH_MODE$|_TASKS_|CLOUD_TASKS|QUEUE', 'Cloud Tasks; local runs inline'),
    (r'DESKTOP_UPDATE', 'desktop update pointers in GCS'),
    # Production user lists: real Omi uids.
    (r'ALLOWLIST|_UIDS?$|COHORT_UIDS', 'production uid lists'),
    (r'^MOBILE_', 'mobile app'),
    # Speech providers the local stack does not run. STT is Deepgram only.
    (r'SONIOX|PARAKEET|MODULATE|^STT_SERVICE_MODELS$|^STT_PRERECORDED_MODEL$', 'speech providers not available'),
    (r'^STT_ROUTING_|^STT_NON_EN_MULTI_PREFER_HINTABLE', 'routing between speech providers not available'),
    (r'^TRANSCRIPTION_(FINAL_PASS|SHADOW)_', 'needs diarizer and other speech providers'),
    (r'^USE_VERTEX_AI$', 'Vertex AI needs Google Cloud credentials'),
    # Omi-operated channels: bots and numbers belong to Omi.
    (r'TELEGRAM|IMESSAGE|MESSAGING|TWILIO|MCP_OAUTH|X_OAUTH|STRIPE', 'channels and integrations run by Omi'),
]
EXCLUDE_RE = [(re.compile(pattern), reason) for pattern, reason in EXCLUDE]

# Our backend container serves both the Cloud Run API and the GKE listen pod.
# On conflicts the listen value wins, since its flags shape recording, except
# where the API owns the feature.
API_WINS = {'PUBLIC_SHARED_CONVERSATION_CHAT_MODE'}


def _env(section: dict) -> dict[str, str]:
    values = {}
    for key, value in (section.get('env') or {}).items():
        if isinstance(value, dict):
            value = value.get('value')
        if value is None or str(value) == 'None':
            continue
        values[key] = str(value)
    return values


def _excluded(key: str) -> str | None:
    for pattern, reason in EXCLUDE_RE:
        if pattern.search(key):
            return reason
    return None


def _write(name: str, values: dict[str, str]) -> tuple[int, dict[str, str]]:
    kept, dropped = {}, {}
    for key in sorted(values):
        reason = _excluded(key)
        if reason:
            dropped[key] = reason
        else:
            kept[key] = values[key]
    lines = [
        f'# Generated by deploy/local/flags/generate.py from {SOURCE_PATH} at {SOURCE_COMMIT}.',
        '# Production values; do not edit by hand. Local overrides go in docker-compose.yaml.',
        *(f'{key}={value}' for key, value in kept.items()),
    ]
    (OUT_DIR / f'{name}.env').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return len(kept), dropped


def main() -> None:
    raw = subprocess.run(
        ['git', 'show', f'{SOURCE_COMMIT}:{SOURCE_PATH}'], capture_output=True, text=True, check=True
    ).stdout
    prod = yaml.safe_load(raw)['environments']['prod']

    api = _env(prod['cloud_run']['services']['backend'])
    listen = _env(prod['gke']['backend-listen'])
    backend = {**api, **listen}
    for key in API_WINS & api.keys():
        backend[key] = api[key]

    services = {
        'backend': backend,
        'pusher': _env(prod['gke']['pusher']),
        'desktop-backend': _env(prod['desktop_backend']),
        'llm-gateway': _env(prod['llm_gateway']),
    }
    for name, values in services.items():
        count, dropped = _write(name, values)
        print(f'{name}: {count} flags, {len(dropped)} left out')


if __name__ == '__main__':
    main()
